#!/usr/bin/env python3
"""Convert lex/v2/unverified.test-vectors to tests/vectors/estream_lex_kat.json.

Usage: python tools/ref_diff/convert_kat.py <path to unverified.test-vectors> [out.json]
"""
import json, re, sys

def parse(text):
    vectors = []
    for blk in re.split(r"(?=Set \d+, vector#\s*\d+:)", text):
        m = re.match(r"Set (\d+), vector#\s*(\d+):", blk)
        if not m:
            continue
        key = re.search(r"key = ([0-9A-F]+)", blk).group(1)
        iv = re.search(r"IV = ([0-9A-F]+)", blk).group(1)
        segs = []
        for sm in re.finditer(r"stream\[(\d+)\.\.(\d+)\] =((?:\s*[0-9A-F]{32})+)", blk):
            segs.append({"start": int(sm.group(1)), "end": int(sm.group(2)), "hex": "".join(sm.group(3).split())})
        dg = re.search(r"xor-digest =((?:\s*[0-9A-F]{32})+)", blk)
        vectors.append({"set": int(m.group(1)), "vector": int(m.group(2)), "key": key, "iv": iv,
                        "stream_length": max(s["end"] for s in segs) + 1,
                        "segments": segs, "xor_digest": "".join(dg.group(1).split())})
    return vectors

if __name__ == "__main__":
    src = sys.argv[1]
    out = sys.argv[2] if len(sys.argv) > 2 else "tests/vectors/estream_lex_kat.json"
    vs = parse(open(src, encoding="utf-8").read())
    json.dump({"source": "LEX-v2 unverified.test-vectors (eSTREAM Phase 3 package)",
               "note": "Generated by the submitter's own C code: consistency check, not independent verification.",
               "stream_definition": "keystream = LEX(key, iv) XOR 0^N; xor_digest = XOR of all 64-byte blocks of the N-byte stream",
               "vectors": vs}, open(out, "w"), indent=1)
    print(f"wrote {out}: {len(vs)} vectors")
